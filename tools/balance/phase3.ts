import { format } from 'prettier'
import type { DifficultyId } from '../../src/content/schema.ts'
import { DIFFICULTIES, EVENTS } from '../../src/engine/day.ts'
import type { Cents } from '../../src/engine/money.ts'
import { formatDollars } from '../sim/cli.ts'
import {
  choiceVerdicts,
  eventTarget,
  TOO_STRONG,
  TOO_WEAK,
  WINDOW_DAYS,
  type ChoiceVerdict,
  type TargetCheck,
} from './eventBranches.ts'
import {
  DAYS_PER_WEEK,
  PERCENTILES,
  percentileRows,
  WEEKS_PER_YEAR,
  type OwnersRun,
} from './owners.ts'

// Writes what `npm run balance -- --percentiles` plays: the percentile
// table the engine reads, src/content/percentiles.json, and the report,
// docs/balance/phase-3.md, with no I/O. The report is for developers, so it
// is in English.

/** One `--percentiles` run: every difficulty's owners. */
export interface PercentileRun {
  readonly years: number
  /** Games per difficulty, on seeds 1 to `games`. */
  readonly games: number
  /** Easiest first. */
  readonly difficulties: readonly OwnersRun[]
}

/**
 * The difficulty the event cards are tuned at: Étienne's decision on #101.
 * The others are shown for information until the cards have numbers of
 * their own per difficulty.
 */
export const TARGET_DIFFICULTY: DifficultyId = 'moyen'

/** The weeks the report shows of the percentile table. */
export const REPORT_WEEKS = [1, 4, 13, 26, 52, 78, 104] as const

/** The command that writes `run`, for the files to name. */
export function command({ years, games }: PercentileRun): string {
  return `npm run balance -- --percentiles --years ${years} --games ${games}`
}

/**
 * `src/content/percentiles.json` for `run`: each difficulty's rows, one a
 * week, each the cumulative Bénéfice net in cents at every percentile of
 * `PERCENTILES`. Laid out by Prettier, as the other content files are, so
 * `npm run format` leaves it as it is.
 */
export async function formatPercentileJson(
  run: PercentileRun,
): Promise<string> {
  const content = {
    _note: `Generated by \`${command(run)}\`: for each difficulty, one row a week from week 1 (days 0 to 6), each the bénéfice net in cents from day 0 to the close of the week's Sunday at each of the percentiles, over that many simulated owners. Do not edit by hand: run the command again, and commit this file with docs/balance/phase-3.md, after any change to the engine or the content that moves the numbers.`,
    games: run.games,
    percentiles: PERCENTILES,
    difficulties: Object.fromEntries(
      run.difficulties.map(({ difficulty, games }) => [
        difficulty,
        percentileRows(games),
      ]),
    ),
  }
  return format(JSON.stringify(content), { parser: 'json' })
}

/**
 * Every card's choices at `run`'s difficulty, summed up over the games:
 * each card a game may draw, with a weight above 0, in the order of the
 * content.
 */
export function eventVerdicts(
  run: OwnersRun,
): { readonly event: string; readonly verdicts: ChoiceVerdict[] }[] {
  return EVENTS.events
    .filter(({ weight }) => weight > 0)
    .map(({ id }) => ({
      event: id,
      verdicts: choiceVerdicts(
        run.games.flatMap(({ events }) =>
          events.filter(({ event }) => event === id),
        ),
      ),
    }))
}

/** The whole report, in Markdown. */
export function formatPhase3Report(run: PercentileRun): string {
  const weeks = run.years * WEEKS_PER_YEAR
  const named = run.difficulties.map((owners) => ({
    owners,
    name: DIFFICULTIES.difficulties[owners.difficulty].name,
    cards: eventVerdicts(owners),
  }))
  const target = named.find(
    ({ owners }) => owners.difficulty === TARGET_DIFFICULTY,
  )
  return [
    '# Balance report: phase 3',
    '',
    `Generated by \`${command(run)}\`, with \`src/content/percentiles.json\`: do not edit by hand, except under the comment at the end that says so. The numbers go stale whenever the engine or the content changes; run the command again then, and commit both files.`,
    '',
    '## What each game plays',
    '',
    `Each difficulty plays seeds 1 to ${run.games}, each game ${weeks} weeks (${weeks * DAYS_PER_WEEK} days) from Monday, May 1st, year 1. The owner of seed n holds one strategy of the grid of \`docs/balance/phase-2.md\` from day 0, drawn at random from the seed, the same at every difficulty. The event cards come up, and the owner answers each with a choice drawn at random, seeded from the game, as \`npm run sim -- --events random\` does.`,
    '',
    '## How other owners did',
    '',
    `The bénéfice net from day 0 to the close of a week's Sunday, after the owner's pay, at each percentile of the ${run.games} games: what « Mieux que N % des propriétaires » compares the player with, through \`percentileOf()\` in \`src/engine/percentiles.ts\`. A percentile is linear between the closest ranks (type 7, as R and NumPy compute by default), rounded half away from zero to the cent. The table shows a few weeks; \`src/content/percentiles.json\` holds all ${weeks}.`,
    '',
    ...named.flatMap(({ owners, name }) => [
      `### ${name}`,
      '',
      ...percentileTable(owners, weeks),
      '',
    ]),
    '## Event cards',
    '',
    `In each game, one occurrence of each card that came up is drawn at random, seeded from the game. From that morning, each choice plays ${WINDOW_DAYS} days, ${WINDOW_DAYS / DAYS_PER_WEEK} weeks with the day of the card, and so does the same morning with no card, the baseline. In every branch, each business day is played with a generator seeded from the game and the day, so they all play the same customers whatever the choice drew before; each choice draws its outcome from a stream of its own. A follow-up queued comes up and is answered at random, the same way in every branch, and no new card is drawn.`,
    '',
    `- **Δ encaisse**: the Encaisse at the close of the ${WINDOW_DAYS}th day, minus the baseline's.`,
    "- **Δ bénéfice net**: the bénéfice net over the window, minus the baseline's.",
    '- **Median**: over the games the card came up in; for an even number, the mean of the middle two, rounded half away from zero to the cent.',
    '- **Best on encaisse**, **Best on bénéfice net**: the share of those games where no other choice of the card did strictly better on that measure; a tie counts for each choice in it. **Best on both** and **Best on neither** follow.',
    '',
    `A choice is too strong when it is best on both in more than ${TOO_STRONG}% of the games, and too weak when it is best on neither in more than ${TOO_WEAK}%. The cards are tuned at ${target?.name ?? TARGET_DIFFICULTY} only (#101); the other difficulties are shown for information. A card that came up in few games is judged on few: the Games column says how many.`,
    '',
    ...(target === undefined
      ? []
      : [
          `### Targets at ${target.name}`,
          '',
          row(['Event', 'Games', 'Verdict']),
          row(['---', '---:', '---']),
          ...target.cards.map(({ event, verdicts }) =>
            targetRow(eventTarget(event, verdicts)),
          ),
          '',
        ]),
    ...named.flatMap(({ name, cards }) => [
      `### ${name}`,
      '',
      row([
        'Event',
        'Choice',
        'Games',
        'Median Δ encaisse',
        'Median Δ bénéfice net',
        'Best on encaisse',
        'Best on bénéfice net',
        'Best on both',
        'Best on neither',
      ]),
      row([
        '---',
        '---',
        '---:',
        '---:',
        '---:',
        '---:',
        '---:',
        '---:',
        '---:',
      ]),
      ...cards.flatMap(({ event, verdicts }) =>
        verdicts.length === 0
          ? [row([event, 'never came up', '0', '', '', '', '', '', ''])]
          : verdicts.map((verdict) => choiceRow(event, verdict)),
      ),
      '',
    ]),
  ].join('\n')
}

function percentileTable(owners: OwnersRun, weeks: number): string[] {
  const rows = percentileRows(owners.games)
  return [
    row(['Week', ...PERCENTILES.map((percentile) => `${percentile}%`)]),
    row(['---:', ...PERCENTILES.map(() => '---:')]),
    ...REPORT_WEEKS.filter((week) => week <= weeks).map((week) =>
      row([
        String(week),
        ...(rows[week - 1] ?? []).map((amount: Cents) => formatDollars(amount)),
      ]),
    ),
  ]
}

function targetRow({
  event,
  games,
  met,
  tooStrong,
  tooWeak,
}: TargetCheck): string {
  if (met === null) return row([event, '0', 'n/a: never came up'])
  const misses = [
    ...tooStrong.map(
      ({ choice, bestOnBoth }) =>
        `${choice} best on both in ${share(bestOnBoth, games)}`,
    ),
    ...tooWeak.map(
      ({ choice, bestOnNeither }) =>
        `${choice} best on neither in ${share(bestOnNeither, games)}`,
    ),
  ]
  return row([event, String(games), met ? '✓' : `✗ ${misses.join('; ')}`])
}

function choiceRow(event: string, verdict: ChoiceVerdict): string {
  const { games } = verdict
  return row([
    event,
    verdict.choice,
    String(games),
    formatDollars(verdict.medianCash),
    formatDollars(verdict.medianNetIncome),
    share(verdict.bestOnCash, games),
    share(verdict.bestOnNetIncome, games),
    share(verdict.bestOnBoth, games),
    share(verdict.bestOnNeither, games),
  ])
}

/**
 * `count` of `games`, as a percentage to a tenth, so that one just over a
 * limit does not read as the limit.
 */
function share(count: number, games: number): string {
  return `${((100 * count) / games).toFixed(1)}%`
}

function row(values: readonly string[]): string {
  return `| ${values.join(' | ')} |`
}
