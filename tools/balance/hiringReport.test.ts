import { describe, expect, it } from 'vitest'
import { candidateIdSchema } from '../../src/content/schema.ts'
import { cents } from '../../src/engine/money.ts'
import { askingWage } from '../../src/engine/staff.ts'
import { HIRING_ROLES, type HiringGame, type HiringRun } from './hiring.ts'
import { formatHiringReport } from './hiringReport.ts'

const at = (cash: number, absences = 0): HiringGame => ({
  cash: cents(cash),
  bankrupt: false,
  absences,
  botched: 0,
  wasted: 0,
})

/** A run of `role` with each candidate `gap(candidate)` above a twin at 0. */
function run(
  role: HiringRun['role'],
  gap: (index: number) => number,
): HiringRun {
  return {
    role,
    difficulty: 'moyen',
    games: 1,
    months: 12,
    twins: [at(0)],
    cells: candidateIdSchema.options.map((candidate, index) => ({
      candidate,
      hourlyWage: askingWage(candidate, role),
      games: [at(gap(index), index === 0 ? 3 : 0)],
    })),
  }
}

describe('formatHiringReport', () => {
  // Amélie, first, is best at the truck, and Kevin, second, everywhere
  // else; Thierry, last, is the weakest, behind everywhere but baking.
  const runs = HIRING_ROLES.map((role) =>
    run(role, (index) =>
      role === 'camion'
        ? index === 0
          ? 500
          : -100 * index
        : role === 'boulanger'
          ? 1000 - 50 * index
          : index === 1
            ? 200
            : -1000,
    ),
  )
  const report = formatHiringReport({ games: 1, months: 12, runs })

  it('says how it was made, and what each role plays', () => {
    expect(report.startsWith('# Balance report: phase 5\n')).toBe(true)
    expect(report).toContain(
      'Generated by `npm run balance -- --hiring --games 1 --months 12`',
    )
    expect(report).toContain('- « Au camion » runs the « busy » truck')
    expect(report).toContain(
      'the contracts of Marché Bio-Logique and Épicerie Chez Normand, signed on day 0 and renewed',
    )
    expect(report).toContain('made at a bakery opened on day 0')
    expect(report.endsWith('|\n')).toBe(true)
  })

  it('reads the targets, ties counted', () => {
    expect(report).toContain(
      '| No candidate is the best hire in every role, ties counted | none is | yes |',
    )
    expect(report).toContain(
      '| The weakest candidate beats no hire in at least one role | Thierry Nguyen, whose best role is « Boulanger », at $4.50 | yes |',
    )
    expect(report).toContain('- « Au camion »: Amélie Gagnon.')
    expect(report).toContain('- « Livreur »: Kevin Bouchard.')
  })

  it('fails the first target when someone is the best everywhere', () => {
    const everywhere = HIRING_ROLES.map((role) =>
      run(role, (index) => (index === 1 ? 900 : -10)),
    )
    expect(
      formatHiringReport({ games: 1, months: 12, runs: everywhere }),
    ).toContain(
      '| No candidate is the best hire in every role, ties counted | Kevin Bouchard is | no |',
    )
  })

  it('lists each role’s candidates by gap, with their traits and asking wage', () => {
    const truck = report.slice(
      report.indexOf('## « Au camion »'),
      report.indexOf('## « Livreur »'),
    )
    const rows = truck
      .split('\n')
      .filter(
        (line) =>
          line.startsWith('| ') &&
          !line.startsWith('| Candidate') &&
          !line.startsWith('| ---'),
      )
    expect(rows).toHaveLength(12)
    expect(rows[0]).toBe(
      '| Amélie Gagnon | Accueil | Rapidité | $18.00 | $5.00 | 3 | 0 | 0 | 0 (0) |',
    )
    expect(rows[1]?.startsWith('| Kevin Bouchard |')).toBe(true)
    expect(rows[11]?.startsWith('| Thierry Nguyen |')).toBe(true)
  })
})
