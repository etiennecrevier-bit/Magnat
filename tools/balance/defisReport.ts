// Writes what `npm run balance -- --defis` plays: the Défis' percentile
// table, src/content/defis-percentiles.json, and the Défis section of
// docs/balance/phase-3.md, between two markers, with no I/O. The report is
// for developers, so it is in English.

/** One `--defis` run: every Défi, in the order of the content. */
export interface DefisBalanceRun {
  /** Games per Défi, on seeds 1 to `games`. */
  readonly games: number
  /** Seeds each strategy of the grid played in the search for the best. */
  readonly search: number
  readonly defis: readonly DefiRun[]
}

/** The first line of the Défis section. */
export const DEFIS_START =
  '<!-- npm run balance -- --defis writes this section. -->'

/** The last line of the Défis section. */
export const DEFIS_END = '<!-- End of the Défis section. -->'

/** Where the Défis section starts and ends. */
export const DEFIS_MARKERS: SectionMarkers = {
  start: DEFIS_START,
  end: DEFIS_END,
}

/** The command that writes `run`, for the files to name. */
export function defisCommand({ games, search }: DefisBalanceRun): string {
  return `npm run balance -- --defis --games ${games} --search ${search}`
}

/**
 * `src/content/defis-percentiles.json` for `run`: for each Défi, its goal's
 * metric, the share of the owners' games that broke a condition, and what
 * the goal measured in the others at every percentile of `PERCENTILES`.
 * Laid out by Prettier, as the other content files are.
 */
export async function formatDefiPercentileJson(
  run: DefisBalanceRun,
): Promise<string> {
  const content = {
    _note: `Generated by \`${defisCommand(run)}\`: for each Défi, how the simulated owners' games ended, for « Mieux que N % des parties simulées ». \`brokenShare\` is the share of the games that broke one of the Défi's conditions; \`values\` holds what the goal's \`metric\` measured in the others at each of the percentiles, in increasing order of the value, null if every game broke one. A game that broke a condition ranks below every other. So a game that broke none is better than N = 100 × (brokenShare + (1 − brokenShare) × p / 100) % of them, where p is the percentile of its value among \`values\` read as \`percentileOf()\` reads percentiles.json (0 below the lowest, the highest percentile at or above the highest, linear in between); for \`spoilageRate\`, where lower is better, p is 100 minus that. A game that broke a condition is better than none. Do not edit by hand: run the command again, and commit this file with docs/balance/phase-3.md, after any change to the engine or the content that moves the numbers.`,
    games: run.games,
    percentiles: PERCENTILES,
    defis: Object.fromEntries(
      run.defis.map(({ defi, owners }) => {
        const { metric } = defiById(DEFIS, defi).goal
        return [
          defi,
          {
            metric,
            brokenShare: fourDecimals(
              medalCounts(owners).broken / owners.length,
            ),
            values: finishedPercentiles(metric, owners),
          },
        ]
      }),
    ),
  }
  return format(JSON.stringify(content), { parser: 'json' })
}

