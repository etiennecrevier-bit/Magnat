function startingCroissants(): number {
  const rule = FOOD_TRUCK.startingDecisions.restock.croissant
  return rule.kind === 'buyDaily' ? rule.quantity : 0
}

function targetRow(played: DefiRun, defi: Defi): string {
  const { metric, medals } = defi.goal
  const check = defiTarget(played)
  const { owners, best } = check
  const misses = [
    check.or ? null : 'or',
    check.argent ? null : 'argent',
    check.bronze ? null : 'bronze',
    check.bestOr ? null : 'best: or',
  ].filter((miss) => miss !== null)
  return row([
    defi.id,
    METRIC_NAMES[metric],
    formatValue(metric, medals.or),
    formatValue(metric, medals.argent),
    formatValue(metric, medals.bronze),
    share(owners.broken, owners.games),
    share(owners.or, owners.games),
    share(owners.argentOrBetter, owners.games),
    share(owners.bronzeOrBetter, owners.games),
    formatStrategy(played.best.strategy, defi),
    share(best.broken, best.games),
    share(best.or, best.games),
    check.met ? '✓' : `✗ ${misses.join(', ')}`,
  ])
}

function outcomeRow(played: DefiRun, defi: Defi): string {
  const { metric } = defi.goal
  const suggested = suggestedThresholds(metric, played.owners)
  const shown = (value: number | null) =>
    value === null ? 'n/a' : formatValue(metric, value)
  return row([
    defi.id,
    ...percentileCells(metric, played.owners),
    shown(suggested.or),
    shown(suggested.argent),
    shown(suggested.bronze),
  ])
}

/** The outcome of `games` at each percentile, worst first, or « broken ». */
function percentileCells(
  metric: DefiMetric,
  games: readonly DefiGame[],
): string[] {
  return PERCENTILES.map((percentile) => {
    const value = outcomeAt(metric, games, percentile)
    return value === null ? 'broken' : formatValue(metric, value)
  })
}

const METRIC_NAMES: Readonly<Record<DefiMetric, string>> = {
  lowestCash: 'lowest cash',
  netIncome: 'net income',
  sales: 'sales',
  customersServed: 'customers served',
  spoilageRate: 'spoilage rate (lower is better)',
  lowestEnergy: 'lowest energy',
}

/** `value` of `metric`, as the report shows it. */
export function formatValue(metric: DefiMetric, value: number): string {
  switch (metric) {
    case 'lowestCash':
    case 'netIncome':
    case 'sales':
      return formatDollars(cents(value))
    case 'customersServed':
      return formatCount(value)
    case 'spoilageRate':
      return `${(100 * value).toFixed(1)}%`
    case 'lowestEnergy':
      return value.toFixed(1)
  }
}

/**
 * `strategy` as it plays in `defi`: prices, croissants bought each day,
 * marketing, days open and the owner's pay, « locked » for a kind the Défi
 * locks.
 */
export function formatStrategy(strategy: Strategy, defi: Defi): string {
  const croissants = defiOwnerChanges(strategy, defi).find(
    (change) => change.kind === 'restock' && change.product === 'croissant',
  )
  const parts: readonly (readonly [DecisionKind, string, string])[] = [
    ['price', 'prices', formatPriceChange(strategy.priceChange)],
    [
      'restock',
      'croissants',
      `${croissants?.kind === 'restock' && croissants.rule.kind === 'buyDaily' ? croissants.rule.quantity : strategy.croissantsPerDay}/day`,
    ],
    [
      'marketingDaily',
      'marketing',
      `${formatDollars(strategy.marketingDaily)}/day`,
    ],
    ['daysOpen', 'days', `${strategy.daysOpen}/week`],
    ['ownerWeeklyPay', 'pay', `${formatDollars(strategy.ownerWeeklyPay)}/week`],
  ]
  return parts
    .map(([kind, label, value]) =>
      defi.locked.includes(kind) ? `${label} locked` : `${label} ${value}`,
    )
    .join(', ')
}

/** `count` of `games`, as a percentage to a tenth. */
function share(count: number, games: number): string {
  return `${((100 * count) / games).toFixed(1)}%`
}

function row(values: readonly string[]): string {
  return `| ${values.join(' | ')} |`
}
