// The phase-5 report, `docs/balance/phase-5.md`: what each candidate makes
// or costs in each role (#255), and whether the targets of step 6 are met.

/** A hiring run, as cli.ts passes it in. */
export interface HiringReportRun {
  readonly games: number
  readonly months: number
  /** One per role, in the order of `HIRING_ROLES`. */
  readonly runs: readonly HiringRun[]
}

/** The phase-5 report, ending with one line break. */
export function formatHiringReport(run: HiringReportRun): string {
  const { games, months, runs } = run
  const verdict = hiringVerdict(runs)
  const lines = [
    '# Balance report: phase 5',
    '',
    `Generated by \`npm run balance -- --hiring --games ${games} --months ${months}\`: do not edit by hand, except under the comment at the end that says so. The numbers go stale whenever the engine or the content changes; run the command again then, and commit the file.`,
    '',
    '## What each game plays',
    '',
    ...playedText(run),
    '',
    '## Targets (#255)',
    '',
    '| Target | Measured | Met |',
    '| --- | --- | --- |',
    `| No candidate is the best hire in every role, ties counted | ${
      verdict.bestEverywhere.length === 0
        ? 'none is'
        : `${verdict.bestEverywhere.map(nameOf).join(', ')} ${verdict.bestEverywhere.length === 1 ? 'is' : 'are'}`
    } | ${verdict.bestEverywhere.length === 0 ? 'yes' : 'no'} |`,
    `| The weakest candidate beats no hire in at least one role | ${nameOf(verdict.weakest.candidate)}, whose best role is « ${roleName(verdict.weakest.role)} », at ${formatDollars(verdict.weakest.gap)} | ${verdict.weakestBeatsNoHire ? 'yes' : 'no'} |`,
    '',
    'The best hire of each role, by median gap, ties all:',
    '',
    ...runs.map(
      ({ role }) =>
        `- « ${roleName(role)} »: ${verdict.best[role].map(nameOf).join(', ')}.`,
    ),
    '',
    ...runs.flatMap((roleRun) => [...roleTable(roleRun), '']),
  ]
  return `${lines.join('\n').trimEnd()}\n`
}

function playedText({ games, months, runs }: HiringReportRun): string[] {
  const difficulty = runs[0]?.difficulty ?? 'moyen'
  const { croissant } = FOOD_TRUCK.products
  const business = (role: StaffRoleId) => {
    const { truck, bakery } = HIRING_BUSINESSES[role]
    const contracts =
      truck.contracts.length === 0
        ? 'no contract'
        : `the contracts of ${truck.contracts
            .map((grocer) => GROCERS.grocers[grocer].name)
            .join(' and ')}, signed on day 0 and renewed`
    const made = bakery
      ? `, its ${truck.croissantsPerDay} croissants a day made at a bakery opened on day 0 with its oven leased, the owner baking them in the twin`
      : `, ${truck.croissantsPerDay} croissants bought a day`
    return `the « ${truck.name} » truck of \`docs/balance/phase-4.md\`, croissants at ${formatDollars(cents(croissant.unitCostCents))} to buy${made}, ${formatDollars(truck.marketingDaily)} of marketing a day, and ${contracts}`
  }
  return [
    `${DIFFICULTIES.difficulties[difficulty].name} plays seeds 1 to ${games} for each role and each of the ${Object.keys(STAFF.candidates).length} candidates, to the close of the last day of month ${months}, or to the close that ends the game in bankruptcy (#160). Each game hires the candidate on day 0, at the wage they ask, \`askingWage()\` in \`src/engine/staff.ts\`, so none quits, and their twin plays the same seed and the same business with nobody hired. The gap is the game's Encaisse less its twin's at the end; it pays the training, the wages and what the employee's strength and weakness do, from \`src/content/staff.json\`. No other event card comes up.`,
    '',
    ...runs.map(
      ({ role }) => `- « ${roleName(role)} » runs ${business(role)}.`,
    ),
    '',
    "Each table shows, by candidate, the median over the seeds: the gap, the days absent with work to do, the units botched at the truck, the owner's and the employee's, and the croissants the baker threw away; « Bankrupt » counts the games that ended in bankruptcy, their twins' in parentheses.",
  ]
}

function roleTable({ role, cells, twins }: HiringRun): string[] {
  const twinsBankrupt = twins.filter(({ bankrupt }) => bankrupt).length
  const rows = cells
    .map((cell) => ({ cell, gap: medianGap(cell, twins) }))
    .sort((a, b) => b.gap - a.gap)
  return [
    `## « ${roleName(role)} »`,
    '',
    `Twins: median Encaisse ${formatDollars(medianCents(twins.map(({ cash }) => cash)))}.`,
    '',
    '| Candidate | Strength | Weakness | Asks an hour | Gap | Days absent | Botched | Thrown away | Bankrupt |',
    '| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |',
    ...rows.map(({ cell, gap }) => {
      const { strength, weakness } = STAFF.candidates[cell.candidate]
      const of = (read: (game: (typeof cell.games)[number]) => number) =>
        formatNumber(median(cell.games.map(read)))
      const bankrupt = cell.games.filter((game) => game.bankrupt).length
      return `| ${nameOf(cell.candidate)} | ${STAFF.traits[strength].name} | ${STAFF.traits[weakness].name} | ${formatDollars(cell.hourlyWage)} | ${formatDollars(gap)} | ${of(({ absences }) => absences)} | ${of(({ botched }) => botched)} | ${of(({ wasted }) => wasted)} | ${bankrupt} (${twinsBankrupt}) |`
    }),
  ]
}

function nameOf(candidate: keyof typeof STAFF.candidates): string {
  return STAFF.candidates[candidate].name
}

function roleName(role: StaffRoleId): string {
  return STAFF.roles[role].name
}

/** A median count: whole, or with its half. */
function formatNumber(value: number): string {
  return Number.isInteger(value) ? String(value) : value.toFixed(1)
}
