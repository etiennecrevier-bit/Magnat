/** How a content file is treated. */
export type FileClass =
  | { readonly file: string; readonly kind: 'balance' }
  | { readonly file: string; readonly kind: 'excluded'; readonly why: string }
  | { readonly file: string; readonly kind: 'unknown' }

/**
 * Each of `files`, the JSON names of src/content/, classified: a balance
 * file, an excluded one, a text file (`*.fr.json`, the player's French), or
 * `unknown`, a file this audit was never told about.
 */
export function classifyFiles(files: readonly string[]): FileClass[] {
  return files
    .filter((file) => file.endsWith('.json'))
    .toSorted()
    .map((file): FileClass => {
      if (file in BALANCE_JSON) return { file, kind: 'balance' }
      const why = EXCLUDED_FILES[file]
      if (why !== undefined) return { file, kind: 'excluded', why }
      if (file.endsWith('.fr.json')) {
        return { file, kind: 'excluded', why: "text: the player's French" }
      }
      return { file, kind: 'unknown' }
    })
}

/** A key of a JSON path: an object's key or an array's index. */
export type PathKey = string | number

/** A numeric leaf of a balance file. */
export interface Tunable {
  readonly file: string
  readonly path: readonly PathKey[]
  /** The path as people read it, items of an array named by their id. */
  readonly label: string
  /**
   * `label` with its difficulty replaced by `*`, the inventory's row; the
   * label itself for a leaf of every difficulty.
   */
  readonly row: string
  readonly value: number
  /** The difficulty the leaf plays at, or null when it plays at all three. */
  readonly difficulty: DifficultyId | null
  readonly actsOn: string
  /**
   * The paths whose values share 1 with this one (segment shares, an
   * outcome's chances): moving it rescales them (see `perturb`).
   */
  readonly shares: readonly (readonly PathKey[])[]
  /** Why it is not moved, or null when it is. */
  readonly excluded: string | null
}

