/** What the leaf at `label` of `file` acts on; null when none says. */
export function actsOn(file: string, label: string): string | null {
  return (
    ACTS_ON.find(([of, pattern]) => of === file && pattern.test(label))?.[2] ??
    null
  )
}

/** The value at `path` of `json`. */
export function getAt(json: unknown, path: readonly PathKey[]): unknown {
  let at: unknown = json
  for (const key of path) {
    if (at === null || typeof at !== 'object') return undefined
    at = (at as Record<PathKey, unknown>)[key]
  }
  return at
}

/** Sets the value at `path` of `json`, in place. */
export function setAt(
  json: unknown,
  path: readonly PathKey[],
  value: unknown,
): void {
  const last = path.at(-1)
  const parent = getAt(json, path.slice(0, -1))
  if (last === undefined || parent === null || typeof parent !== 'object') {
    throw new RangeError(`No value at ${path.join('.')}`)
  }
  ;(parent as Record<PathKey, unknown>)[last] = value
}

/** The id or kind that names an item of an array, if it has one. */
function itemName(item: unknown, index: number): string {
  if (item !== null && typeof item === 'object') {
    const { id, kind, event } = item as Record<string, unknown>
    if (typeof id === 'string') return id
    if (typeof event === 'string') return event
    if (typeof kind === 'string') return `${index}:${kind}`
  }
  return String(index)
}

/** Every tunable of `json`, the content of `file`, in document order. */
export function tunablesOf(file: string, json: unknown): Tunable[] {
  const found: Tunable[] = []
  const walk = (at: unknown, path: PathKey[], label: string): void => {
    if (typeof at === 'number') {
      found.push(leaf(file, json, path, label, at))
      return
    }
    if (Array.isArray(at)) {
      const numbers = at.every((item) => typeof item === 'number')
      at.forEach((item, index) =>
        walk(
          item,
          [...path, index],
          `${label}[${numbers ? index : itemName(item, index)}]`,
        ),
      )
      return
    }
    if (at !== null && typeof at === 'object') {
      for (const [key, value] of Object.entries(at)) {
        walk(value, [...path, key], label === '' ? key : `${label}.${key}`)
      }
    }
  }
  walk(json, [], '')
  return found
}

function leaf(
  file: string,
  json: unknown,
  path: readonly PathKey[],
  label: string,
  value: number,
): Tunable {
  const difficulty =
    path.find(
      (key): key is DifficultyId =>
        typeof key === 'string' && DIFFICULTIES.includes(key),
    ) ?? null
  const row =
    difficulty === null
      ? label
      : label.replace(new RegExp(`(^|\\.)${difficulty}(\\.|$)`), '$1*$2')
  const shares = sharesOf(json, path)
  const quantity = NOT_A_QUANTITY.find(([pattern]) => pattern.test(label))
  const excluded =
    quantity !== undefined
      ? quantity[1]
      : shares.length === 0 && /\.chance$/.test(label) && value === 1
        ? 'the only outcome of its choice'
        : null
  return {
    file,
    path,
    label,
    row,
    value,
    difficulty,
    actsOn: actsOn(file, row) ?? '',
    shares,
    excluded,
  }
}

/** The paths that share 1 with `path`'s value, if it is a share. */
function sharesOf(json: unknown, path: readonly PathKey[]): PathKey[][] {
  const last = path.at(-1)
  const parentPath = path.slice(0, -1)
  if (parentPath.at(-1) === 'segmentShares') {
    const parent = getAt(json, parentPath) as Record<string, unknown>
    return Object.keys(parent)
      .filter((key) => key !== last)
      .map((key) => [...parentPath, key])
  }
  // An outcome's chance: events[e].choices[c].outcomes[o].chance.
  if (last === 'chance' && path.at(-3) === 'outcomes') {
    const outcomesPath = path.slice(0, -2)
    const outcomes = getAt(json, outcomesPath) as unknown[]
    const index = path.at(-2)
    return outcomes
      .map((_, each) => each)
      .filter((each) => each !== index)
      .map((each) => [...outcomesPath, each, 'chance'])
  }
  return []
}

/** Every tunable of every balance file, in the inventory's order. */
export function inventory(
  jsons: Readonly<Record<string, unknown>> = BALANCE_JSON,
): Tunable[] {
  return Object.entries(jsons).flatMap(([file, json]) => tunablesOf(file, json))
}

/** A tunable moved by a factor, or why it could not be. */
export type Perturbation =
  | {
      readonly ok: true
      /** The moved content of the tunable's file. */
      readonly json: unknown
      /** The tunable's new value. */
      readonly value: number
      /** What happened on the way: rounded back, clamped, shares rescaled. */
      readonly note: string
    }
  | { readonly ok: false; readonly why: string }

/**
 * `json`, the content of `tunable.file`, with the tunable's value times
 * `factor`: rounded half up when it counts whole things, or moved by one
 * when that rounds back to it, and kept between 0 and 1 when it is a
 * probability. Its shares (see `Tunable.shares`) are
 * rescaled so they still sum to what they did. Not ok when the value does
 * not move (0, or rounded back) or the game's loaders refuse it (see
 * `validate`): a whole number is tried when the loaders refuse a fraction.
 */
export function perturb(
  json: unknown,
  tunable: Tunable,
  factor: number,
): Perturbation {
  if (tunable.excluded !== null) return { ok: false, why: tunable.excluded }
  const { value } = tunable
  if (value === 0) return { ok: false, why: '0 does not move' }
  const raw = value * factor
  const probability = PROBABILITY.test(tunable.label)
  const clamped = probability ? Math.min(1, Math.max(0, raw)) : raw
  const whole = WHOLE.test(tunable.label) && Number.isInteger(value)
  // A whole number too small to move by the factor moves by one instead.
  const rounded = roundHalfUp(clamped)
  const step =
    rounded === value && Number.isInteger(value)
      ? value + Math.sign(factor - 1)
      : rounded
  const tries = (whole ? [step] : [clamped, step]).filter(
    (each, index, all) => all.indexOf(each) === index,
  )
  let why = ''
  for (const moved of tries) {
    if (moved === value) {
      why = `rounds back to ${value}`
      continue
    }
    const copy = structuredClone(json)
    setAt(copy, tunable.path, moved)
    const notes: string[] = []
    if (clamped !== raw) notes.push(`clamped to ${clamped}`)
    if (moved !== clamped) {
      notes.push(
        moved === roundHalfUp(clamped)
          ? `rounded to ${moved}`
          : `moved by one, ${percentMoved(value, moved)}`,
      )
    }
    if (tunable.shares.length > 0) {
      if (!rescaleShares(copy, tunable, value, moved)) {
        why = 'its shares cannot make room'
        continue
      }
      notes.push('shares rescaled')
    }
    const refused = validate(tunable.file, copy)
    if (refused !== null) {
      why = `the loaders refuse ${moved}: ${refused}`
      continue
    }
    return { ok: true, json: copy, value: moved, note: notes.join(', ') }
  }
  return { ok: false, why }
}

/**
 * Rescales, in `json`, the shares of `tunable` so all of them sum to what
 * they did once it moved from `before` to `after`. False when the others
 * are all 0 and cannot give or take.
 */
function rescaleShares(
  json: unknown,
  tunable: Tunable,
  before: number,
  after: number,
): boolean {
  const others = tunable.shares.map((path) => ({
    path,
    value: getAt(json, path) as number,
  }))
  const rest = others.reduce((total, { value }) => total + value, 0)
  if (rest === 0) return false
  const scale = (rest + before - after) / rest
  if (scale < 0) return false
  for (const { path, value } of others) setAt(json, path, value * scale)
  return true
}

/** How far `after` is from `before`, as a signed whole percentage. */
function percentMoved(before: number, after: number): string {
  const percent = Math.round(((after - before) / Math.abs(before)) * 100)
  return `${percent > 0 ? '+' : ''}${percent} %`
}

/** Rounds half up, so 2.5 is 3 and -2.5 is -2. */
export function roundHalfUp(value: number): number {
  return Math.floor(value + 0.5)
}

/**
 * Why the game's loaders refuse `json` as `file`, with the other content
 * as shipped and the files that check against it checked again; null when
 * they accept it.
 */
export function validate(file: string, json: unknown): string | null {
  try {
    switch (file) {
      case 'foodtruck.json': {
        const truck = loadFoodTruckContent(json)
        loadCustomerContent(undefined, truck)
        loadDistrictContent(undefined, truck)
        loadPlacesContent(undefined, truck)
        break
      }
      case 'segments.json':
        loadCustomerContent(json)
        break
      case 'districts.json':
        loadDistrictContent(json)
        break
      case 'difficulty.json':
        loadDistrictContent(undefined, undefined, loadDifficultyContent(json))
        break
      case 'bakery.json':
        loadBakeryContent(json)
        break
      case 'energy.json':
        loadEnergyContent(json)
        break
      case 'personal.json':
        loadPersonalContent(json)
        break
      case 'staff.json':
        loadStaffContent(json)
        break
      case 'dream.json':
        loadDreamContent(json)
        break
      case 'events.json': {
        const events = loadEventContent(json)
        loadGrocerContent(undefined, events)
        loadFinancingContent(undefined, events)
        loadDefiContent(undefined, events)
        break
      }
      case 'grocers.json':
        loadGrocerContent(json)
        break
      case 'financing.json':
        loadFinancingContent(json)
        break
      case 'places.json':
        loadPlacesContent(json)
        break
      default:
        return `${file} is no balance file`
    }
    return null
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error)
    return message.split('\n').slice(0, 2).join(' ').slice(0, 160)
  }
}
