import { format } from 'prettier'
import { describe, expect, it } from 'vitest'
import {
  difficultyIdSchema,
  loadPercentileContent,
  type DifficultyId,
} from '../../src/content/schema.ts'
import { EVENTS } from '../../src/engine/day.ts'
import { cents } from '../../src/engine/money.ts'
import type { EventSample } from './eventBranches.ts'
import { ownerStrategy, PERCENTILES, type OwnerGame } from './owners.ts'
import {
  formatPercentileJson,
  formatPhase3Report,
  REPORT_WEEKS,
  type PercentileRun,
} from './phase3.ts'

// What `npm run balance -- --percentiles` writes, from owners made up here:
// the percentile table the engine loads, and the report.

/** A game whose bénéfice net goes by `step` a week, with `events`. */
function game(
  seed: number,
  weeks: number,
  step: number,
  events: readonly EventSample[] = [],
): OwnerGame {
  return {
    seed,
    strategy: ownerStrategy(seed),
    weeklyNetIncome: Array.from({ length: weeks }, (_, week) =>
      cents(step * (week + 1)),
    ),
    events,
  }
}

/** grosseCommande, where « Accepter » is best on both. */
const ORDER: EventSample = {
  event: 'grosseCommande',
  day: 15,
  choices: [
    { choice: 'accepter', cash: cents(100), netIncome: cents(500) },
    { choice: 'payeLivraison', cash: cents(50), netIncome: cents(50) },
    { choice: 'refuser', cash: cents(0), netIncome: cents(0) },
  ],
}

/** formulaire14B, where each choice wins one of two games. */
function fine(day: number, contest: number): EventSample {
  return {
    event: 'formulaire14B',
    day,
    choices: [
      { choice: 'payer', cash: cents(-15_000), netIncome: cents(-15_000) },
      { choice: 'contester', cash: cents(contest), netIncome: cents(contest) },
    ],
  }
}

function run(weeks: number): PercentileRun {
  const owners = (difficulty: DifficultyId) => ({
    difficulty,
    games: [
      game(1, weeks, -1000, [ORDER, fine(30, -20_000)]),
      game(2, weeks, 2000, [fine(40, 0)]),
      game(3, weeks, 500),
    ],
  })
  return {
    years: weeks / 52,
    games: 3,
    difficulties: difficultyIdSchema.options.map(owners),
  }
}

describe('formatPercentileJson', () => {
  it('writes a table the engine loads, the same for the same run, as Prettier lays it out', async () => {
    const text = await formatPercentileJson(run(52))
    expect(await formatPercentileJson(run(52))).toBe(text)
    expect(await format(text, { parser: 'json' })).toBe(text)
    const table = loadPercentileContent(JSON.parse(text))
    expect(table.games).toBe(3)
    expect(table.percentiles).toEqual([...PERCENTILES])
    expect(table.difficulties.moyen).toHaveLength(52)
    // Week 1 of the three games: -1000, 500 and 2000.
    expect(table.difficulties.facile[0]).toEqual([
      -850, -700, -400, -100, 200, 500, 800, 1100, 1400, 1700, 1850,
    ])
    expect(JSON.parse(text)._note).toMatch(
      /^Generated by `npm run balance -- --percentiles --years 1 --games 3`/,
    )
  })

  it('keeps two years of every difficulty under 300 KB, even with the largest amounts', async () => {
    const huge = (difficulty: DifficultyId) => ({
      difficulty,
      games: [game(1, 104, -99_999_999), game(2, 104, 99_999_999)],
    })
    const text = await formatPercentileJson({
      years: 2,
      games: 2,
      difficulties: difficultyIdSchema.options.map(huge),
    })
    expect(Buffer.byteLength(text)).toBeLessThan(300_000)
  })
})

describe('formatPhase3Report', () => {
  const report = formatPhase3Report(run(104))

  it('has the sections of the report, each difficulty in turn', () => {
    expect(report.split('\n').filter((line) => line.startsWith('#'))).toEqual([
      '# Balance report: phase 3',
      '## What each game plays',
      '## How other owners did',
      '### Facile',
      '### Moyen',
      '### Difficile',
      '## Event cards',
      '### Targets at Moyen',
      '### Facile',
      '### Moyen',
      '### Difficile',
    ])
    expect(report).toMatch(
      /^# Balance report: phase 3\n\nGenerated by `npm run balance -- --percentiles --years 2 --games 3`/,
    )
  })

  it('shows the percentiles of a few weeks', () => {
    const weeks = report
      .split('\n')
      .filter((line) => /^\| \d+ \| [-$]/.test(line))
      .map((line) => Number(line.split(' | ')[0]?.slice(2)))
    expect(weeks).toEqual([...REPORT_WEEKS, ...REPORT_WEEKS, ...REPORT_WEEKS])
    expect(report).toContain(
      '| 1 | -$8.50 | -$7.00 | -$4.00 | -$1.00 | $2.00 | $5.00 | $8.00 | $11.00 | $14.00 | $17.00 | $18.50 |',
    )
  })

  it('judges every card a game may draw at Moyen, those that never came up included', () => {
    const start = report.indexOf('### Targets at Moyen')
    const targets = report
      .slice(start, report.indexOf('### Facile', start))
      .split('\n')
      .filter((line) => line.startsWith('| ') && !/^\| (Event|---) /.test(line))
    expect(targets.map((line) => line.split(' | ')[0]?.slice(2))).toEqual(
      EVENTS.events.filter(({ weight }) => weight > 0).map(({ id }) => id),
    )
    expect(targets).toContain(
      '| grosseCommande | 1 | ✗ accepter best on both in 100.0%; payeLivraison best on neither in 100.0%; refuser best on neither in 100.0% |',
    )
    expect(targets).toContain('| formulaire14B | 2 | ✓ |')
    expect(targets).toContain('| chalet | 0 | n/a: never came up |')
  })

  it('sums up each choice over the games its card came up in', () => {
    expect(report).toContain(
      '| formulaire14B | payer | 2 | -$150.00 | -$150.00 | 50.0% | 50.0% | 50.0% | 50.0% |',
    )
    expect(report).toContain(
      '| formulaire14B | contester | 2 | -$100.00 | -$100.00 | 50.0% | 50.0% | 50.0% | 50.0% |',
    )
    expect(report).toContain('| chalet | never came up | 0 |  |  |  |  |  |  |')
  })
})
